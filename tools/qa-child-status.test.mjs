import { strict as assert } from 'node:assert';
import { spawnSync } from 'node:child_process';
import { qaChildStatus, qaFailureAnnotation } from './qa-child-status.mjs';

const child = (script, options = {}) => spawnSync(process.execPath, ['-e', script], { encoding: 'utf8', ...options });
assert.equal(qaChildStatus(child('process.exit(0)')).code, 0);
assert.equal(qaChildStatus(child('process.exit(7)')).code, 7);
const killed = qaChildStatus(child("process.kill(process.pid, 'SIGTERM')"));
assert.equal(killed.code, 1);
assert.match(killed.error, /SIGTERM/);
const timeout = qaChildStatus(child('setTimeout(() => {}, 5000)', { timeout: 150 }));
assert.equal(timeout.code, 1);
assert.match(timeout.error, /ETIMEDOUT/);
const annotation = qaFailureAnnotation({ name: 'Stage 100%', code: 1, stdout: 'first\nsecond', stderr: 'failure\r\nlast' });
assert.match(annotation, /^::error title=HM26 QA failed::/);
assert.ok(annotation.includes('100%25') && annotation.includes('first%0Asecond') && annotation.includes('failure%0D%0Alast'));
assert.ok(!annotation.includes('\n') && !annotation.includes('\r'));
const longAnnotation = qaFailureAnnotation({ name: 'Long browser run', code: 1, stdout: `❌ early assertion\n${'passing tail '.repeat(500)}`, stderr: '' });
assert.ok(longAnnotation.includes('❌ early assertion'), 'early failed checks must survive tail truncation');
console.log('✅ QA runner reports exit errors, signals and timeouts; CI annotations are escaped');
